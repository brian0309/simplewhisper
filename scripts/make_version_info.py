"""Write the Windows version resource for the frozen executables.

The version is read from pyproject.toml so the executable properties and
the package metadata never drift apart. Run it before PyInstaller:

    python scripts/make_version_info.py

With ``--print-version`` it only writes the version to stdout, which is how
build.bat passes the version to the installer.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path
from typing import Tuple

ROOT = Path(__file__).resolve().parent.parent
TARGET = ROOT / "scripts" / "version_info.txt"

TEMPLATE = """# Generated by scripts/make_version_info.py - do not edit.
VSVersionInfo(
  ffi=FixedFileInfo(
    filevers=({filevers}),
    prodvers=({filevers}),
    mask=0x3f,
    flags=0x0,
    OS=0x40004,
    fileType=0x1,
    subtype=0x0,
    date=(0, 0)
  ),
  kids=[
    StringFileInfo(
      [
        StringTable(
          '040904B0',
          [StringStruct('CompanyName', 'SimpleWhisper'),
           StringStruct('FileDescription', 'SimpleWhisper - local speech-to-text'),
           StringStruct('FileVersion', '{version}'),
           StringStruct('InternalName', '{internal}'),
           StringStruct('LegalCopyright', 'MIT'),
           StringStruct('OriginalFilename', '{original}'),
           StringStruct('ProductName', 'SimpleWhisper'),
           StringStruct('ProductVersion', '{version}')])
      ]),
    VarFileInfo([VarStruct('Translation', [1033, 1200])])
  ]
)
"""


def read_version_text() -> str:
    """The version from pyproject.toml, exactly as written there."""
    text = (ROOT / "pyproject.toml").read_text(encoding="utf-8")
    match = re.search(r'^version\s*=\s*"([^"]+)"', text, re.MULTILINE)
    return match.group(1) if match else "0.0.0"


def read_version() -> Tuple[int, int, int, int]:
    """The version from pyproject.toml, as four numbers."""
    numbers = []
    for part in read_version_text().split(".")[:4]:
        numbers.append(int(part) if part.isdigit() else 0)
    while len(numbers) < 4:
        numbers.append(0)
    return tuple(numbers)  # type: ignore[return-value]


def main() -> int:
    numbers = read_version()
    version = ".".join(str(number) for number in numbers)

    if "--print-version" in sys.argv[1:]:
        print(read_version_text())
        return 0

    TARGET.write_text(
        TEMPLATE.format(
            filevers=", ".join(str(number) for number in numbers),
            version=version,
            internal="simplewhisper",
            original="SimpleWhisper.exe",
        ),
        encoding="utf-8",
    )
    print(f"version resource: {TARGET} ({version})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
